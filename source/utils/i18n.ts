const BROWSER_LANG_MAP: Record<string, string> = {
  'zh-CN': 'zh_CN',
  'zh-TW': 'zh_TW',
  'zh-HK': 'zh_TW',
  de: 'de',
  es: 'es',
  ja: 'ja',
  ko: 'ko',
  ru: 'ru',
};

function detectSystemLocale(): string {
  const uiLang = browser.i18n.getUILanguage();
  const direct = BROWSER_LANG_MAP[uiLang];
  if (direct) {
    return direct;
  }
  const base = uiLang.split('-')[0] ?? '';
  const mapped = BROWSER_LANG_MAP[base];
  if (mapped) {
    return mapped;
  }
  return 'en';
}

export type ThemeMode = 'system' | 'light' | 'dark';
export type DensityMode = 'compact' | 'comfortable';

const APPEARANCE_KEY = 'coolhusky_appearance';

let currentLocale: LocaleCode = 'system';
let currentTheme: ThemeMode = 'light';
let currentDensity: DensityMode = 'compact';

export function getCurrentLocale(): LocaleCode {
  return currentLocale;
}
export function getCurrentTheme(): ThemeMode {
  return currentTheme;
}
export function getCurrentDensity(): DensityMode {
  return currentDensity;
}

const listeners = new Set<() => void>();

function notify(): void {
  listeners.forEach((listener) => listener());
}

export function subscribeAppearance(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function getResolvedLocale(): string {
  return currentLocale === 'system' ? detectSystemLocale() : currentLocale;
}

// Stale write guard
let manualChangeVersion = 0;

export function setLocale(locale: LocaleCode): void {
  manualChangeVersion += 1;
  currentLocale = locale;
  notify();
}

export function setTheme(theme: ThemeMode): void {
  manualChangeVersion += 1;
  currentTheme = theme;
  applyTheme(theme);
  notify();
}

export function setDensity(density: DensityMode): void {
  manualChangeVersion += 1;
  currentDensity = density;
  notify();
}

export async function loadAppearance(): Promise<void> {
  const versionAtStart = manualChangeVersion;
  const result = await browser.storage.local.get(APPEARANCE_KEY);
  // Stale restore guard
  if (versionAtStart !== manualChangeVersion) {
    return;
  }

  const stored = result[APPEARANCE_KEY] as Record<string, unknown> | undefined;
  if (stored) {
    if (stored.locale && LOCALE_OPTIONS.some((o) => o.code === stored.locale)) {
      currentLocale = stored.locale as LocaleCode;
    }
    if (
      stored.theme &&
      ['system', 'light', 'dark'].includes(String(stored.theme))
    ) {
      currentTheme = stored.theme as ThemeMode;
    }
    if (
      stored.density &&
      ['compact', 'comfortable'].includes(String(stored.density))
    ) {
      currentDensity = stored.density as DensityMode;
    }
  }
  applyTheme(currentTheme);
  notify();
}

export async function saveAppearance(): Promise<void> {
  await browser.storage.local.set({
    [APPEARANCE_KEY]: {
      locale: currentLocale,
      theme: currentTheme,
      density: currentDensity,
    },
  });
}

function applyTheme(theme: ThemeMode): void {
  const root = document.documentElement;
  const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  const isDark = theme === 'dark' || (theme === 'system' && prefersDark);
  root.classList.toggle('dark', isDark);
  root.style.colorScheme = isDark ? 'dark' : 'light';
}

function activeMessages(): Messages {
  const resolved = getResolvedLocale();
  return messagesMap[resolved] ?? messagesMap['en'] ?? {};
}

export function t(key: string, substitutions?: string | string[]): string {
  const msg = activeMessages()[key] ?? messagesMap['en']?.[key] ?? key;
  if (!substitutions) {
    return msg;
  }
  const subs = Array.isArray(substitutions) ? substitutions : [substitutions];
  return msg.replace(/\$(\d+)/g, (_, n) => subs[parseInt(n) - 1] ?? '');
}
